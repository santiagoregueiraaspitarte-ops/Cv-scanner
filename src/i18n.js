export const STRINGS = { en: EN, es: ES };

/** Look up a string; `{name}` placeholders are filled from params. Falls back to English, then the key. */
export function t(lang, key, params = {}) {
  const table = STRINGS[lang] || EN;
  const s = key in table ? table[key] : key in EN ? EN[key] : key;
  if (typeof s === 'function') return s(params);
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
}

export function normalizeLang(lang, fallback = 'en') {
  return LANGS.includes(lang) ? lang : fallback;
}

// ---------- CV language detection ----------
// Counts common function words of each language (accents ignored). Spanish wins only with a clear
// lead, so short or mixed texts default to English. Deterministic: same text, same answer.
const ES_WORDS = new Set(('de la el los las del en y con para por una un al se que como su sus mas años experiencia ' +
  'gestion equipo equipos desarrollo empresa ventas lidere logre cliente clientes area proyectos educacion habilidades ' +
  'formacion universidad licenciatura actualidad presente trabajo').split(' '));
const EN_WORDS = new Set(('the and of to in with for on at by an as from is was were years experience team teams ' +
  'development company sales led achieved client clients projects education skills university bachelor present work').split(' '));

export function detectLanguage(text) {
  const words = String(text == null ? '' : text).toLowerCase().normalize('NFD').replace(/\p{M}+/gu, '')
    .match(/\p{L}+/gu) || [];
  let es = 0;
  let en = 0;
  for (const w of words) {
    if (ES_WORDS.has(w)) es++;
    else if (EN_WORDS.has(w)) en++;
  }
  return es >= 5 && es > en * 1.2 ? 'es' : 'en';
}
